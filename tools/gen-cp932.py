#!/usr/bin/env python3
"""Generate src/cp932.rs, the Shift_JIS table the STS reader decodes names with.

    python3 tools/gen-cp932.py > src/cp932.rs

The table is CP932 — Shift_JIS as Japanese Windows has it, NEC and IBM
extensions included — because シラヘイタイムシート was a Japanese Windows
application, and it is Python's own `cp932` codec that fills it, so the
table is that codec's and not something typed in. One u16 per double-byte
code: the lead byte (0x81-0x9F, 0xE0-0xFC) picks a row of 189, the trail
byte (0x40-0xFC) the place in it, and 0 means the code has no character.
"""

import sys

LEADS = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
TRAILS = range(0x40, 0xFD)

table = []
for lead in LEADS:
    for trail in TRAILS:
        try:
            ch = bytes([lead, trail]).decode("cp932")
        except UnicodeDecodeError:
            table.append(0)
            continue
        assert len(ch) == 1 and ord(ch) <= 0xFFFF, (hex(lead), hex(trail), ch)
        table.append(ord(ch))

out = sys.stdout
out.write("// Generated by tools/gen-cp932.py from Python's cp932 codec. Do not edit.\n")
out.write("\n")
out.write("/// Codes to a lead byte: trail bytes 0x40-0xFC. The lead bytes are 0x81-0x9F,\n")
out.write("/// then 0xE0-0xFC, one row each.\n")
out.write("pub(crate) const ROW: usize = 189;\n\n")
out.write("/// One code point per double-byte code, 0 for none.\n")
out.write("#[rustfmt::skip]\n")
out.write(f"pub(crate) static TABLE: [u16; {len(table)}] = [\n")
for i in range(0, len(table), 12):
    out.write("    " + " ".join(f"0x{c:04x}," for c in table[i:i + 12]) + "\n")
out.write("];\n")
